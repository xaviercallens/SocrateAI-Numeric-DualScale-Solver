def test_phase12_orchestrator_convergence():
    report = run_phase12_pipeline()
    assert report["certificate"]["overall_status"] == "CERTIFIED"
    assert report["certificate"]["problems_converged"]["H66_aerospace_scramjet"] is True

    # All loops must converge to CERTIFIED status
    for loop_name, loop_res in report["loops"].items():
        assert loop_res["final_status"] == "CERTIFIED", (
            f"{loop_name} did not converge: {loop_res['best_result']}"
        )
        # Must have run at least 1 real iteration
        assert loop_res["iterations_run"] >= 1, f"{loop_name} ran 0 iterations"
        # Ratchet: best_fitness must be present and positive
        assert loop_res["best_fitness"] > 0, f"{loop_name} best_fitness={loop_res['best_fitness']}"

    # SHA-256 must be unique per run (includes timestamp) and non-trivial
    cert_hash = report["certificate"]["sha256_hash"]
    assert len(cert_hash) == 64, "SHA-256 must be a 64-hex-char string"
    assert cert_hash != "0" * 64, "SHA-256 must not be trivially zero"


