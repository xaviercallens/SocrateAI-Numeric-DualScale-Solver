def test_temperature_breaker_detection():
    """Verify the temperature breaker logic: after 3 stagnant iterations, stuck flag is set."""
    # Build a synthetic history with 3 stagnant entries
    from dualscale_solver.agents.phase12_workflow_orchestrator import _aero_hypothesis

    # Simulate 3 iterations that all failed to improve
    stagnant_history = []
    for i in range(3):
        stagnant_history.append({
            "iteration": i + 1,
            "hypothesis": {"spectral_filter_coef": 2.0 + i * 0.1},
            "sim_result": {
                "sbli_horizon": 4.0,  # below target
                "unstart": False,
                "enstrophy": 18.0,
            },
            "fitness_score": 3.0,  # same fitness = stagnation
            "ratchet_decision": "REVERT",
            "stuck_in_local_minimum": (i == 2),  # only last entry gets the flag
        })

    # When stuck_in_local_minimum is True, the generator should make a radical jump
    result = _aero_hypothesis(stagnant_history)
    delta = result["spectral_filter_coef"] - 2.2  # prev_coef was 2.2 (last hypothesis)
    assert delta >= 1.5, (
        f"Temperature breaker should cause radical jump (delta >= 1.5) but got delta={delta:.2f}"
    )
    assert "STUCK" in result.get("reasoning", "").upper() or "RADICAL" in result.get("reasoning", "").upper(), (
        f"Reasoning should mention stuck/radical but got: {result.get('reasoning', '')}"
    )


