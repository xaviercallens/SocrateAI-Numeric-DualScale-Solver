def test_ratchet_monotonic_fitness():
    """The ratchet must guarantee that best_fitness never decreases across iterations."""
    report = run_phase12_pipeline()
    for loop_name, loop_res in report["loops"].items():
        history = loop_res["history"]
        best_seen = -float("inf")
        for entry in history:
            recorded_best = entry["best_fitness"]
            assert recorded_best >= best_seen, (
                f"[{loop_name}] Ratchet violated: best_fitness decreased from "
                f"{best_seen} to {recorded_best} at iteration {entry['iteration']}"
            )
            best_seen = recorded_best


